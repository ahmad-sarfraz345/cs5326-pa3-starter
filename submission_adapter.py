def aggregate_path_score(
    step_scores: list[float], 
    strategy: str = "min", 
    penalty_lambda: float = 2.0
) -> float:
    """Aggregates a list of step scores into a single path scalar score.
    
    Rules:
      - An empty list returns -1.0 for every strategy.
      - 'min': min(step_scores).
      - 'product': p_t = clamp((r_t + 1)/2, 0.01, 0.99); returns the raw product.
      - 'step_penalty': mean(step_scores) - penalty_lambda * count(r_t == -1.0).
      - An unknown strategy raises ValueError.
        
    Args:
        step_scores: List of float scores for each step in the path (+1.0 or -1.0).
        strategy: Aggregation strategy name ('min', 'product', or 'step_penalty').
        penalty_lambda: Penalty weight for erroneous steps in 'step_penalty' (default 2.0).
        
    Returns:
        Aggregated scalar score as a float.
    """
